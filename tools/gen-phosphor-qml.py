#!/usr/bin/env python3
"""Generate modules/common/PhosphorIcons.qml from the dots-icon-font codepoint table.

The font has no ligatures, so QML addresses a glyph by codepoint. Codepoints are
plane 16 (surrogate pairs in JS), so the file holds hex literals and builds the
string with String.fromCodePoint, never a literal character or a \\u escape.

Only names the shell uses are emitted. Convention: bare name = regular weight,
`<name>-fill` = filled. Run with no arguments to rewrite the file, or with
--stdout to print it (tests/icons.sh compares the two).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = os.path.join(ROOT, "home/private_dot_config/quickshell/dots/modules")
TSV = os.path.join(ROOT, "nix/pkgs/dots-icon-font/codepoints.tsv")
OUT = os.path.join(MODULES, "common/PhosphorIcons.qml")

_LIT = re.compile(r'"([a-z][a-z0-9_-]*)"')


class LIT:
    @staticmethod
    def findall(s):
        # drop string comparisons such as `kind === "brightness"` first
        return _LIT.findall(re.sub(r'[!=]==?\s*"[^"]*"', "", s))


def registry():
    reg = {}
    with open(TSV, encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.rstrip("\n").split("\t")
            reg[cols[0]] = int(cols[4], 16)
    return reg


def used_names():
    found = set()
    for dp, dn, fn in os.walk(MODULES):
        dn[:] = [d for d in dn if d != "tst"]
        for f in fn:
            if not f.endswith(".qml"):
                continue
            src = open(os.path.join(dp, f), encoding="utf-8").read()
            for m in re.finditer(r"\b(?:Icon|Glyph)\s*\{", src):
                i, d = m.end(), 1
                while i < len(src) and d:
                    d += (src[i] == "{") - (src[i] == "}")
                    i += 1
                body = src[m.end():i - 1]
                for km in re.finditer(r"(?:^|[;{,\s])(?:name|text|icon)\s*:", body):
                    # value runs to the next `;` or closing brace (single-line blocks)
                    # or end of line (multi-line blocks)
                    rest = body[km.end():].split("\n", 1)[0]
                    found.update(LIT.findall(re.split(r"[;}]", rest)[0]))
            # `icons: ({ key: "name", ... })` map literals
            for m in re.finditer(r"\b\w*[Ii]cons\s*:\s*\(\s*\{", src):
                i, d = m.end(), 1
                while i < len(src) and d:
                    d += (src[i] == "{") - (src[i] == "}")
                    i += 1
                found.update(LIT.findall(src[m.end():i - 1]))
            for ln in src.splitlines():
                if re.match(r"\s*(?:\{\s*)?icon\s*:", ln) or re.search(r"[{,;]\s*icon\s*:", ln):
                    tail = ln.split("icon:", 1)[1]
                    found.update(LIT.findall(re.split(r",\s*[a-z]+\s*:", tail)[0]))
    return found


def render():
    reg = registry()
    base = sorted(n for n in used_names() if n in reg and not n.endswith("-fill"))
    rows = []
    for n in base:
        fill = reg.get(n + "-fill")
        rows.append('    "%s": [0x%X, %s]' % (n, reg[n], "0x%X" % fill if fill else "0"))
    body = ",\n".join(rows)
    return f"""pragma Singleton
import QtQuick

// GENERATED by tools/gen-phosphor-qml.py from nix/pkgs/dots-icon-font/codepoints.tsv.
// Do not edit; rerun the generator (tests/icons.sh fails if this file drifts).
// `dots Icons` has no ligatures, so a glyph is addressed by codepoint. Codepoints are
// plane 16, so they are hex literals turned into a string by String.fromCodePoint.
// Each entry is [regular, fill]; fill is 0 when the font has no filled variant.
QtObject {{
  readonly property var table: ({{
{body}
  }})

  // The glyph for `name`. `fill` picks the filled weight when one exists.
  // An unknown name comes back unchanged, so legacy callers show readable text, not tofu.
  function cp(name, fill) {{
    var e = table[name];
    if (!e) return name;
    return String.fromCodePoint(fill && e[1] ? e[1] : e[0]);
  }}
}}
"""


if __name__ == "__main__":
    text = render()
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
